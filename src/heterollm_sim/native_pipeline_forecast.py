"""Conditional max-plus composition of measured native pipeline stages."""
from __future__ import annotations

from collections import defaultdict
from dataclasses import dataclass, asdict
import math
import re
from statistics import fmean
from typing import Any, Mapping, Sequence

PP_BOUNDARY_STATE_ASSUMPTION = (
    "Measured PP cohort boundaries represent later controller, allocator, KV, activation and PD states."
)
PP_RESOURCE_ORDER_ASSUMPTION = (
    "Measured resource predecessor order and stage/microbatch dependencies remain valid during composition."
)


def forecast_complete_request_metrics(*, decode_measurement=None, virtual_requests=()):
    """Return request-level TPOT samples from explicit token evidence only.

    Cohort step duration and ``mean_iteration_ns`` are deliberately not
    accepted as substitutes.  A conditional forecast may provide explicit
    virtual output-token timestamps generated by its FIFO model.
    """
    values = {}
    measurement = decode_measurement if isinstance(decode_measurement, Mapping) else {}
    direct = measurement.get("complete_request_tpot_ns")
    if isinstance(direct, Mapping):
        for request_id, value in direct.items():
            if isinstance(value, (int, float)) and math.isfinite(float(value)) and float(value) >= 0:
                values[str(request_id)] = float(value)
    for row in virtual_requests:
        if not isinstance(row, Mapping):
            continue
        request_id = str(row.get("request_id", ""))
        if not request_id or request_id in values:
            continue
        times = row.get("output_token_times_ns")
        if isinstance(times, Sequence) and not isinstance(times, (str, bytes)) and len(times) >= 2:
            numbers = [float(value) for value in times]
            if all(math.isfinite(value) and value >= 0 for value in numbers) and all(
                    right >= left for left, right in zip(numbers, numbers[1:])):
                values[request_id] = (numbers[-1] - numbers[0]) / (len(numbers) - 1)
    if not values:
        return {"accepted": False, "reason": "complete_request_tpot_unavailable", "samples": {}}
    samples = tuple(values.values())
    return {"accepted": True, "reason": None, "samples": values,
            "mean_complete_request_tpot_ns": fmean(samples),
            "max_complete_request_tpot_ns": max(samples)}


@dataclass(frozen=True)
class PipelineStageSample:
    cohort: int
    microbatch: int
    stage: int
    start_ns: float
    end_ns: float
    kind: str = "compute"
    target_stage: int | None = None
    dependencies: tuple[str, ...] = ()

    def __post_init__(self):
        if any(type(v) is not int or v < 0 for v in (self.cohort, self.microbatch, self.stage)):
            raise ValueError("PP cohort, microbatch and stage must be nonnegative integers")
        if self.kind not in {"compute", "pipeline_activation_transfer"}:
            raise ValueError("unsupported PP sample kind")
        if (not all(math.isfinite(float(v)) for v in (self.start_ns, self.end_ns))
                or self.start_ns < 0 or self.end_ns < self.start_ns):
            raise ValueError("invalid PP sample interval")

    @property
    def duration_ns(self):
        return self.end_ns - self.start_ns


@dataclass(frozen=True)
class NativePipelineForecast:
    cutoff_ns: float
    sampled_decode_cohorts: int
    predicted_decode_cohorts: int
    sampled_visible_output_tokens: int
    predicted_visible_output_tokens: int
    metrics: Mapping[str, Any]
    metric_bounds: Mapping[str, Any]
    stage_samples: tuple[Mapping[str, Any], ...]
    virtual_request_metrics: tuple[Mapping[str, Any], ...]
    error_budget: Mapping[str, Any]

    def to_metadata(self):
        return {"schema": "native-pipeline-window-forecast/v2", **asdict(self),
                "forecast_has_physical_trace": False,
                "controller_state": "discarded_after_physical_pipeline_samples"}


def _interval(lo, hi):
    if not (math.isfinite(lo) and math.isfinite(hi) and 0 <= lo <= hi):
        raise ValueError("invalid PP interval")
    return {"lower": lo, "upper": hi, "estimate": (lo + hi) / 2,
            "relative_error_budget": (hi - lo) / (lo + hi) if lo + hi else 0.}


def _sample_interval(values, limit, *, allow_zero=False):
    if not values or any(not math.isfinite(v) or v < 0 for v in values):
        raise ValueError("invalid PP service samples")
    # The physical samples already form the observed envelope.  Expanding the
    # min/max range by the maximum deviation from the mean double-counted the
    # same cohort variation and made a two-cohort sample reject otherwise
    # stable stage/transfer services before composition.  Keep the empirical
    # envelope and let the independent-budget gate reject genuinely wide
    # samples; additional cohorts are used by the caller when the envelope is
    # not stable enough.
    lo, hi = max(0., min(values)), max(values)
    relative = (hi - lo) / (hi + lo) if hi + lo else 0.
    if (not allow_zero and lo <= 0) or relative > limit:
        raise ValueError("native_pipeline_independent_budget_exceeded")
    return lo, hi


def compose_pipeline_window(samples: Sequence[PipelineStageSample | Mapping[str, Any]], *,
        sampled_decode_cohorts: int, predicted_decode_cohorts: int, batch_size: int,
        output_tokens: int, cutoff_ns: float = 0., target_relative_error: float = .10,
        warmup_decode_cohorts: int = 0, physical_prefix_decode_cohorts: int | None = None,
        allow_zero_physical_prefix: bool = False,
        cohort_prefix_samples_ns: Sequence[float] = (),
        cohort_suffix_samples_ns: Sequence[float] = ()):
    """Forecast a flush-at-cohort-boundary PP window from real stage services.

    ``predicted_decode_cohorts`` names the whole requested measurement window.
    Its already observed prefix is counted once. A short representative prefix
    may also forecast the remaining warmup, which contributes no measured tokens.
    """
    if not 0 < target_relative_error < 1:
        raise ValueError("target_relative_error must be between zero and one")
    if (sampled_decode_cohorts < 1 or predicted_decode_cohorts < 1
            or warmup_decode_cohorts < 0 or batch_size < 1 or output_tokens < 2):
        raise ValueError("invalid PP cohort counts or batch/output")
    physical = sampled_decode_cohorts if physical_prefix_decode_cohorts is None else physical_prefix_decode_cohorts
    total_cohorts = warmup_decode_cohorts + predicted_decode_cohorts
    if ((not allow_zero_physical_prefix and physical < sampled_decode_cohorts)
            or (allow_zero_physical_prefix and physical < 0)
            or physical > total_cohorts):
        raise ValueError("invalid PP physical prefix")
    rows = tuple(row if isinstance(row, PipelineStageSample) else PipelineStageSample(**row) for row in samples)
    cohorts = set(range(sampled_decode_cohorts))
    if not rows or {r.cohort for r in rows} != cohorts:
        raise ValueError("insufficient PP samples")
    grouped = defaultdict(list)
    present = defaultdict(set)
    for row in rows:
        key = (row.microbatch, row.stage, row.kind)
        grouped[key].append(row.duration_ns)
        present[key].add(row.cohort)
    limit = target_relative_error / (2 + target_relative_error)
    # Validate complete keys before rejecting an incomplete grid.  If an
    # otherwise complete stage already violates the independent error budget,
    # report that concrete cause instead of hiding it behind a topology error.
    intervals = {}
    for key, values in grouped.items():
        if len(values) == sampled_decode_cohorts and present[key] == cohorts:
            intervals[key] = _sample_interval(values, limit, allow_zero=key[2] != "compute")
    if any(found != cohorts or len(grouped[key]) != sampled_decode_cohorts for key, found in present.items()):
        raise ValueError("native_pipeline_inconsistent_sample_topology")
    prefix = _sample_interval(tuple(cohort_prefix_samples_ns) or (0.,), limit, allow_zero=True)
    suffix = _sample_interval(tuple(cohort_suffix_samples_ns) or (0.,), limit, allow_zero=True)
    microbatches = sorted({row.microbatch for row in rows})
    stages = sorted({row.stage for row in rows if row.kind == "compute"})
    if not stages or any((mb, stage, "compute") not in intervals for mb in microbatches for stage in stages):
        raise ValueError("native_pipeline_incomplete_stage_grid")
    template = []
    available_lo = dict.fromkeys(stages, prefix[0])
    available_hi = dict.fromkeys(stages, prefix[1])
    transfer_lo, transfer_hi = {}, {}
    for mb in microbatches:
        prior_lo, prior_hi = prefix
        for position, stage in enumerate(stages):
            lo, hi = intervals[(mb, stage, "compute")]
            start_lo, start_hi = max(available_lo[stage], prior_lo), max(available_hi[stage], prior_hi)
            end_lo, end_hi = start_lo + lo, start_hi + hi
            template.append({"microbatch": mb, "stage": stage, "kind": "compute",
                "start_ns": start_lo, "start_upper_ns": start_hi, "end_ns": end_lo,
                "end_upper_ns": end_hi, "dependencies": [f"stage_fifo:{stage}"] +
                ([f"transfer:{stages[position - 1]}:mb:{mb}"] if position else [])})
            available_lo[stage], available_hi[stage] = end_lo, end_hi
            prior_lo, prior_hi = end_lo, end_hi
            if position + 1 < len(stages):
                key = (mb, stage, "pipeline_activation_transfer")
                if key not in intervals:
                    raise ValueError("native_pipeline_activation_transfer_sample_missing")
                lo, hi = intervals[key]
                start_lo, start_hi = max(end_lo, transfer_lo.get(stage, 0.)), max(end_hi, transfer_hi.get(stage, 0.))
                prior_lo, prior_hi = start_lo + lo, start_hi + hi
                transfer_lo[stage], transfer_hi[stage] = prior_lo, prior_hi
                template.append({"microbatch": mb, "stage": stage, "kind": "pipeline_activation_transfer",
                    "start_ns": start_lo, "start_upper_ns": start_hi, "end_ns": prior_lo,
                    "end_upper_ns": prior_hi, "dependencies": [f"stage:{stage}:mb:{mb}"]})
    step_lo = max(row["end_ns"] for row in template) + suffix[0]
    step_hi = max(row["end_upper_ns"] for row in template) + suffix[1]
    step = _interval(step_lo, step_hi)
    compute_rows = [row for row in template if row["kind"] == "compute"]
    transfer_rows = [row for row in template if row["kind"] == "pipeline_activation_transfer"]
    if not compute_rows:
        raise ValueError("native_pipeline_complete_request_tpot_unavailable")
    # A complete request crosses the steady stage service plus the activation
    # edge and half of the fill/drain bubble. This is the request-level FIFO
    # model; the raw flush makespan remains ``step_service_ns``.
    compute_lo = [row["end_ns"] - row["start_ns"] for row in compute_rows]
    compute_hi = [row["end_upper_ns"] - row["start_upper_ns"] for row in compute_rows]
    transfer_lo = [row["end_ns"] - row["start_ns"] for row in transfer_rows] or [0.0]
    transfer_hi = [row["end_upper_ns"] - row["start_upper_ns"] for row in transfer_rows] or [0.0]
    request_interval = _interval(
        max(compute_lo) + max(transfer_lo) + .5 * (min(compute_lo) + max(transfer_lo)),
        max(compute_hi) + max(transfer_hi) + .5 * (min(compute_hi) + max(transfer_hi)))
    measurement = _interval(predicted_decode_cohorts * step_lo, predicted_decode_cohorts * step_hi)
    measured_tokens = predicted_decode_cohorts * batch_size
    bounds = {"step_service_ns": step, "mean_complete_request_tpot_ns": step,
        "measurement_duration_ns": measurement,
        "cluster_tokens_per_second": _interval(measured_tokens * 1e9 / measurement["upper"],
                                               measured_tokens * 1e9 / measurement["lower"])}
    future = []
    origin_lo = origin_hi = float(cutoff_ns)
    for cohort in range(physical, total_cohorts):
        for row in template:
            future.append({**row, "cohort": cohort, "measurement": cohort >= warmup_decode_cohorts,
                "start_ns": origin_lo + row["start_ns"],
                "start_upper_ns": origin_hi + row["start_upper_ns"],
                "end_ns": origin_lo + row["end_ns"], "end_upper_ns": origin_hi + row["end_upper_ns"]})
        origin_lo += step_lo
        origin_hi += step_hi
    relative = max(((hi - lo) / (hi + lo) if hi + lo else 0.)
                   for lo, hi in (*intervals.values(), prefix, suffix))
    virtual = tuple({"request_id": f"virtual-{index}", "status": "forecast_completed",
        "output_token_times_ns": tuple(float(index * step["estimate"] + token * request_interval["estimate"])
                                        for token in range(output_tokens)),
        "tpot_interval_ns": request_interval, "visible_output_tokens": output_tokens,
        "metric_semantics": "conditional_complete_request_tpot"}
        for index in range(min(batch_size, 64)))
    request_metrics = forecast_complete_request_metrics(virtual_requests=virtual)
    if not request_metrics["accepted"]:
        raise ValueError(request_metrics["reason"])
    request_interval = {**request_interval, "metric_semantics": "complete_request_tpot_from_virtual_token_timestamps"}
    observed_measurement = max(0, physical - warmup_decode_cohorts)
    return NativePipelineForecast(float(cutoff_ns), sampled_decode_cohorts, predicted_decode_cohorts, 0,
        (predicted_decode_cohorts - observed_measurement) * batch_size,
        {**{key: interval["estimate"] for key, interval in bounds.items()},
         "mean_complete_request_tpot_ns": request_metrics["mean_complete_request_tpot_ns"]},
        {**bounds, "mean_complete_request_tpot_ns": request_interval}, tuple(future), virtual,
        {"target_relative_error": target_relative_error, "effective_independent_target": limit,
         "relative_error": relative, "conditional_only": True,
         "interval_method": "observed_min_max_envelope_v2",
         "assumptions": [PP_BOUNDARY_STATE_ASSUMPTION, PP_RESOURCE_ORDER_ASSUMPTION],
         "physical_runtime_state_advanced": False, "sampled_stage_count": len(intervals),
         "sampled_cohort_count": sampled_decode_cohorts, "physical_prefix_decode_cohorts": physical,
         "requested_warmup_decode_cohorts": warmup_decode_cohorts,
         "predicted_warmup_decode_cohorts": max(0, warmup_decode_cohorts - physical),
         "measurement_visible_output_tokens": measured_tokens,
         "cohort_prefix_ns": _interval(*prefix), "cohort_suffix_ns": _interval(*suffix)})


def samples_from_execution_schedule(rows: Sequence[Mapping[str, Any]], *, cohort: int) -> tuple[PipelineStageSample, ...]:
    """Extract only authored PP operator stages; controller work is overhead."""
    grouped = {}
    for row in rows:
        group = str(row.get("invocation_group_id") or "")
        if not group:
            continue
        match = re.search(r"-(\d+)$", group)
        if match is None:
            raise ValueError("native_pipeline_microbatch_identity_unavailable")
        microbatch = int(match.group(1))
        stage_id = str(row.get("stage_id", ""))
        transfer = re.search(r"\.pp(\d+)\.activation_transfer$", stage_id)
        compute = re.search(r"\.stage(\d+)$", stage_id)
        if transfer is None and compute is None:
            continue
        kind = "pipeline_activation_transfer" if transfer is not None else "compute"
        stage = int((transfer or compute).group(1))
        key = (microbatch, stage, kind)
        item = grouped.get(key)
        if item is None:
            grouped[key] = [float(row["start_ns"]), float(row["end_ns"]),
                            tuple(str(parent) for parent in row.get("dependencies", ()))]
        else:
            item[0] = min(item[0], float(row["start_ns"]))
            item[1] = max(item[1], float(row["end_ns"]))
    return tuple(PipelineStageSample(cohort, mb, stage, lo, hi, kind,
        target_stage=stage + 1 if kind == "pipeline_activation_transfer" else None, dependencies=dependencies)
        for (mb, stage, kind), (lo, hi, dependencies) in grouped.items())


